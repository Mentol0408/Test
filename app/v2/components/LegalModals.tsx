export function LegalModals() {
  const [open, setOpen] = useState<number | null>(null);

  useEffect(() => {
    if (open == null) return;
    document.body.style.overflow = "hidden";
    const onKey = (e: KeyboardEvent) => e.key === "Escape" && setOpen(null);
    window.addEventListener("keydown", onKey);
    return () => {
      document.body.style.overflow = "";
      window.removeEventListener("keydown", onKey);
    };
  }, [open]);

  const doc = open != null ? DOCS[open] : null;

  return (
    <>
      {DOCS.map((d, i) => (
        <li key={d.title}>
          <button
            onClick={() => setOpen(i)}
            className="text-left text-sm text-[var(--rw-muted)] transition-colors hover:text-[var(--rw-text)]"
          >
            {d.title}
          </button>
        </li>
      ))}

      {doc && (
        <div className="fixed inset-0 z-[120] flex items-center justify-center p-4" onClick={() => setOpen(null)}>
          <div className="absolute inset-0 bg-black/80 backdrop-blur-md" />
          <div
            role="dialog"
            aria-modal="true"
            aria-label={doc.title}
            onClick={(e) => e.stopPropagation()}
            className="relative flex max-h-[86vh] w-full max-w-2xl flex-col overflow-hidden rounded-2xl border border-[var(--rw-line-2)] bg-[var(--rw-bg-2)]"
          >
            <div className="flex items-center justify-between gap-4 border-b border-[var(--rw-line)] px-6 py-4">
              <h2 className="rw-display text-lg font-bold uppercase tracking-tight">{doc.title}</h2>
              <button
                onClick={() => setOpen(null)}
                aria-label="Закрыть"
                className="flex h-9 w-9 items-center justify-center rounded-lg border border-[var(--rw-line-2)] text-[var(--rw-muted)] hover:text-[var(--rw-text)]"
              >
                ×
              </button>
            </div>
            <div className="rw-scroll overflow-y-auto px-6 py-5">
              {doc.blocks.map((b, i) =>
                typeof b === "string" ? (
                  <p key={i} className="mb-3 text-sm leading-relaxed text-[var(--rw-muted)]">{b}</p>
                ) : (
                  <h3 key={i} className="mb-2 mt-5 text-[15px] font-bold text-[var(--rw-text)]">{b.h}</h3>
                ),
              )}
            </div>
          </div>
        </div>
      )}
    </>
  );
}
